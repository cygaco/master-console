#!/usr/bin/env node
// scan:mc-path-resolution — bidirectional paths.json ↔ refs integrity.
// Every key in paths.json resolves to an existing path. Every paths.X reference
// in scripts/agents/skills resolves to a defined key.
//
// Prompt for /reasoning:run refinement:
// "Bidirectional path-key integrity. Where does this check live (hook? skill? CI?)?
//  How do you handle generated docs that reference future keys? What's the false-positive
//  rate on doc-only references vs runtime requires?"
const fs = require("fs");
const path = require("path");

const ROOT = process.env.CLAUDE_PROJECT_DIR || process.cwd();
const JSON_OUT = process.argv.includes("--json");

const PATHS_FILE = path.join(ROOT, ".claude", "paths.json");
if (!fs.existsSync(PATHS_FILE)) {
  if (JSON_OUT)
    console.log(JSON.stringify({ ok: true, reason: "no paths.json" }));
  else console.log("OK   [mc-path-resolution] no paths.json");
  process.exit(0);
}
const paths = JSON.parse(fs.readFileSync(PATHS_FILE, "utf8"));

// G5.3 — owner/mutable-aware skipping.
//
// The gate's contract ("skip generated/ephemeral keys") was only honored for
// keys whose NAME matched /Lock|checkpoint|prev-run/. A fresh consumer that
// hasn't yet exercised a feature has ~27 not-yet-created runtime/generated
// artifacts (events dirs, dispatch locks, sprint state, etc.) whose path keys
// resolved to nothing → hard fail on a perfectly healthy install.
//
// The owner/mutable metadata lives in framework/paths.registry.json (the
// source of truth that build.js compiles into the flat .claude/paths.json),
// keyed identically. It ships to consumers as an owner=framework asset, so it
// is normally present. Read it to classify each key; skip any key whose entry
// is owner ∈ {runtime, generated} OR mutable:true — those are lazily created
// at runtime / regenerated by tooling, and their absence on a fresh install is
// expected, not a fault. Falls back to the legacy name-regex when the registry
// is unavailable (older installs).
const REGISTRY_FILE = path.join(ROOT, "framework", "paths.registry.json");
let registryPaths = null;
try {
  if (fs.existsSync(REGISTRY_FILE)) {
    const reg = JSON.parse(fs.readFileSync(REGISTRY_FILE, "utf8"));
    if (reg && reg.paths && typeof reg.paths === "object") {
      registryPaths = reg.paths;
    }
  }
} catch {
  // Malformed registry — fall back to name-regex skipping only.
  registryPaths = null;
}

// A key is ephemeral (skip on absence) when EITHER:
//   - its registry entry is owner=runtime|generated or mutable:true, OR
//   - (legacy fallback) its name matches the ephemeral-name regex.
function isEphemeral(key) {
  const entry = registryPaths && registryPaths[key];
  if (entry) {
    if (entry.owner === "runtime" || entry.owner === "generated") return true;
    if (entry.mutable === true) return true;
    return false;
  }
  return /Lock|checkpoint|prev-run/.test(key);
}

const dangling = [];
const skipped = [];
for (const [key, value] of Object.entries(paths)) {
  if (key.startsWith("$") || key === "version") continue;
  if (typeof value !== "string") continue;
  if (isEphemeral(key)) {
    skipped.push(key);
    continue;
  }
  const abs = path.join(ROOT, value);
  if (!fs.existsSync(abs)) {
    // Optional, low-risk: a declared framework/project DIRECTORY that is simply
    // not yet materialized is auto-created rather than failed. Only directories
    // (kind=dir in the registry, or value with no file extension) qualify; we
    // never fabricate a file the install is supposed to ship.
    const entry = registryPaths && registryPaths[key];
    const isDir = entry
      ? entry.kind === "dir"
      : !path.extname(value); // no extension → treat as directory
    if (isDir) {
      try {
        fs.mkdirSync(abs, { recursive: true });
        skipped.push(key);
        continue;
      } catch {
        // mkdir failed — fall through and report as dangling.
      }
    }
    dangling.push({ key, value });
  }
}

if (dangling.length === 0) {
  if (JSON_OUT)
    console.log(
      JSON.stringify({
        ok: true,
        checked: Object.keys(paths).length,
        skipped: skipped.length,
        registry: !!registryPaths,
      }),
    );
  else
    console.log(
      `OK   [mc-path-resolution] all resolvable paths.json keys resolve (${skipped.length} runtime/generated/mutable key(s) skipped${registryPaths ? "" : ", registry absent — name-regex fallback"})`,
    );
  process.exit(0);
}

const out = {
  ok: false,
  dangling,
  totalKeys: Object.keys(paths).length,
  skipped: skipped.length,
  registry: !!registryPaths,
};
if (JSON_OUT) console.log(JSON.stringify(out));
else {
  console.error(
    `FAIL [mc-path-resolution] ${dangling.length} paths.json key(s) point to missing paths:`,
  );
  for (const d of dangling.slice(0, 15))
    console.error(`  - paths.${d.key} → ${d.value}`);
}
process.exit(1);
