test("computeCoverage: phrasing derives every number from the emitted table (real registry + real baseline)", () => {
  const registry = loadRegistry(path.join(__dirname, "gate-failclosed-registry.json"));
  const baseline = loadBaseline(path.join(__dirname, "gate-failclosed-baseline.json"));
  const coverage = computeCoverage(registry.rows, baseline);
  assert.equal(coverage.M, baseline.site_ids.length);
  assert.ok(coverage.N >= 0 && coverage.N <= coverage.M);
  assert.ok(coverage.K >= 0 && coverage.K <= coverage.M);
  assert.ok(coverage.phrasing.includes(String(coverage.M)));
  assert.ok(coverage.phrasing.includes(String(coverage.N)));
  assert.ok(coverage.phrasing.includes(String(coverage.K)));
  assert.ok(coverage.phrasing.includes(baseline.detector_sha));
});

test("real repo end-to-end run against scripts/ + the real registry/baseline produces a well-formed report", () => {
  const result = runEnforcer({ root: "scripts", baseDir: REPO_ROOT });
  assert.ok(typeof result.exitCode === "number");
  assert.ok(Array.isArray(result.new_entrants));
  assert.ok(Array.isArray(result.regressed));
  assert.equal(result.regressed.length, 0);
});

test("real ledgers: every baseline site and registry row cites a line of code inside its file", () => {
  const result = runEnforcer({ root: "scripts", baseDir: REPO_ROOT });
  assert.deepEqual(result.stale_cites, []);
});

const PLANTED_PREFIX = "scripts/checks/fixtures/gate-failclosed/";

