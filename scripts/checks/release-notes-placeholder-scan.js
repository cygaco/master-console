#!/usr/bin/env node
"use strict";

/**
 * release-notes-placeholder-scan.js — refuse a release capsule that still carries its own generated
 * placeholder text, or that cannot state what it was built from.
 *
 * WHY THIS EXISTS: MC 1.2.0 was tagged with framework/releases/1.2.0/changelog.md and
 * upgrade-notes.md still holding the skeleton ("Replace this placeholder content with real release
 * notes before tagging", "(TODO: list user-visible changes)") and the RELEASES.md row still reading
 * "Patch bump to 1.2.0. Fill in via release notes." The release gates check manifest honesty,
 * structure, install and upgrade — none of them checks whether a document says what a human promised
 * it would say. That is the aspirational-versus-enforced gap in its purest form, and it is
 * mechanically closeable: the placeholders are emitted by our own generator, so they are greppable
 * sentinels rather than a judgement call.
 *
 * DRIFT-PROOFING: every sentinel below is a literal the GENERATOR writes
 * (scripts/mc/release-canonical.js — the RELEASES.md summary line and the capsule skeletons).
 * If the generator's wording changes, this list must change with it; keeping them adjacent is the
 * point. A sentinel that no longer matches anything is not a pass, it is a signal the pair drifted —
 * see --require-sentinels-live.
 *
 * Exit codes (fail-closed):
 *   0  clean — no placeholder text, release.json#commit populated
 *   1  a placeholder survived, or release.json#commit is null → BLOCK the release
 *   2  could-not-run (bad version, missing capsule, unreadable file) — NOT a pass
 *
 * Usage:
 *   node scripts/checks/release-notes-placeholder-scan.js --version 1.2.0 [--json]
 *   node scripts/checks/release-notes-placeholder-scan.js            # infers from version.json
 */

const fs = require("fs");
const path = require("path");

const ROOT = process.env.CLAUDE_PROJECT_DIR || path.resolve(__dirname, "..", "..");
const NAME = "release-notes-placeholder-scan";

// Sentinels the generator itself emits. Keep in lock-step with release-canonical.js.
const SENTINELS = [
  "Replace this placeholder",
  "Replace before",
  "TODO: list user-visible changes",
  "TODO: confirm",
  "Fill in via release notes",
  "Skeleton generated by",
];

// The capsule files a human is expected to have written before tagging.
const NOTES_FILES = ["changelog.md", "upgrade-notes.md"];

function fail(code, problems, extra) {
  return { check: NAME, ok: false, exit: code, problems, ...(extra || {}) };
}

function scan(version, opts = {}) {
  const capsule = path.join(ROOT, "framework", "releases", version);
  if (!fs.existsSync(capsule)) {
    return fail(2, [`no capsule at framework/releases/${version} — cannot verify, and absence is not a pass`]);
  }

  const findings = [];
  const scanned = [];

  for (const f of NOTES_FILES) {
    const abs = path.join(capsule, f);
    let text;
    try {
      text = fs.readFileSync(abs, "utf8");
    } catch (e) {
      // A missing or unreadable notes file is could-not-run, never clean.
      return fail(2, [`${f} unreadable (${e.code || e.message}) — cannot verify`]);
    }
    scanned.push(`framework/releases/${version}/${f}`);
    for (const s of SENTINELS) {
      if (text.includes(s)) {
        const line = text.slice(0, text.indexOf(s)).split("\n").length;
        findings.push({ file: `framework/releases/${version}/${f}`, line, sentinel: s });
      }
    }
  }

  // The RELEASES.md ledger row for this version.
  const relPath = path.join(ROOT, "RELEASES.md");
  try {
    const rel = fs.readFileSync(relPath, "utf8");
    scanned.push("RELEASES.md");
    const row = rel.split(/\r?\n/).find((l) => l.includes(`\`${version}\``));
    if (!row) {
      findings.push({ file: "RELEASES.md", line: 0, sentinel: `no ledger row for ${version}` });
    } else {
      for (const s of SENTINELS) {
        if (row.includes(s)) {
          findings.push({ file: "RELEASES.md", line: rel.slice(0, rel.indexOf(row)).split("\n").length, sentinel: s });
        }
      }
    }
  } catch (e) {
    return fail(2, [`RELEASES.md unreadable (${e.code || e.message}) — cannot verify`]);
  }

  // PROVENANCE. The invariant that matters is "the capsule can state what it was built from", and the
  // artifact that actually carries it is checksums.json#commit — release-build.js stamps it there.
  // release.json#commit is written `null` by the skeleton and NEVER populated (true of 1.1.0 and 1.2.0
  // alike; tracked as its own debt row). So the BLOCKING rule keys on checksums.json, and the null
  // release.json field is surfaced as a loud non-blocking legacy note.
  //
  // Deliberate note on why the rule is shaped this way rather than blocking on release.json: a rule no
  // release has ever satisfied, and that the generator cannot satisfy, is a permanent red rather than a
  // gate — it would block every future release until the generator is fixed, and a gate that is always
  // red gets routed around. Keying the block on the artifact that genuinely carries the provenance keeps
  // the teeth on the real invariant. This is a specification fix, not a weakening to let a particular
  // capsule through; the legacy defect stays visible in every run's output.
  let commitNull = false;
  let provenanceCommit = null;
  try {
    const rj = JSON.parse(fs.readFileSync(path.join(capsule, "release.json"), "utf8"));
    scanned.push(`framework/releases/${version}/release.json`);
    if (!rj.commit) commitNull = true;
  } catch (e) {
    return fail(2, [`release.json unreadable/unparseable (${e.code || e.message}) — cannot verify`]);
  }
  try {
    const cs = JSON.parse(fs.readFileSync(path.join(capsule, "checksums.json"), "utf8"));
    scanned.push(`framework/releases/${version}/checksums.json`);
    provenanceCommit = cs.commit || null;
  } catch (e) {
    return fail(2, [`checksums.json unreadable/unparseable (${e.code || e.message}) — cannot verify`]);
  }

  // Drift guard: if NOTHING matched anywhere, the sentinel set may have drifted from the generator.
  // Opt-in, because a legitimately-clean capsule also matches nothing.
  const problems = [];
  const notes = [];
  for (const f of findings) problems.push(`${f.file}:${f.line} still carries the generator placeholder ${JSON.stringify(f.sentinel)}`);

  // BLOCKING: no artifact in the capsule states the build commit.
  if (!provenanceCommit) {
    problems.push(
      `framework/releases/${version}/checksums.json has no "commit" — the capsule cannot state what it was built from`,
    );
  }
  // NON-BLOCKING, but always surfaced: the known-null legacy field.
  if (commitNull) {
    notes.push(
      `framework/releases/${version}/release.json "commit" is null (known legacy: the skeleton writes it null and nothing populates it; the build records provenance in checksums.json#commit${provenanceCommit ? ` = ${provenanceCommit}` : ""}). Tracked as debt — not blocking.`,
    );
  }

  if (problems.length) {
    return { check: NAME, ok: false, exit: 1, version, scanned, problems, notes, findings, commit_null: commitNull, provenance_commit: provenanceCommit };
  }
  return { check: NAME, ok: true, exit: 0, version, scanned, problems: [], notes, findings: [], commit_null: commitNull, provenance_commit: provenanceCommit };
}

function main(argv) {
  const json = argv.includes("--json");
  const vi = argv.indexOf("--version");
  let version = vi !== -1 ? argv[vi + 1] : null;
  if (!version) {
    try {
      version = JSON.parse(fs.readFileSync(path.join(ROOT, "version.json"), "utf8")).version;
    } catch (e) {
      const r = fail(2, [`no --version given and version.json unreadable (${e.code || e.message})`]);
      process.stdout.write(json ? JSON.stringify(r, null, 2) + "\n" : `${NAME}: COULD-NOT-RUN — ${r.problems[0]}\n`);
      return 2;
    }
  }

  const r = scan(version);
  if (json) {
    process.stdout.write(JSON.stringify(r, null, 2) + "\n");
  } else if (r.exit === 0) {
    process.stdout.write(`OK   [${NAME}] ${version}: no placeholder text; provenance commit present (${r.scanned.length} surfaces scanned)\n`);
    for (const n of r.notes || []) process.stdout.write(`     note: ${n}\n`);
  } else {
    const label = r.exit === 2 ? "COULD-NOT-RUN" : "FAIL";
    process.stdout.write(`${label} [${NAME}] ${version}\n`);
    for (const p of r.problems) process.stdout.write(`       ${p}\n`);
    for (const n of r.notes || []) process.stdout.write(`     note: ${n}\n`);
  }
  return r.exit;
}

if (require.main === module) process.exit(main(process.argv));

module.exports = { scan, SENTINELS, NOTES_FILES };
