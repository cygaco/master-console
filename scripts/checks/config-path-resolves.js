const NOT_SCRIPT_SCOPE_RE = /(?:^|\/)(?:fixtures?|__fixtures__|tests?)\/|\.test\.|(?:^|\/)test-[^/]*$/;
const SPAWN_CALL_RE = /\b(?:spawnSync|spawn|execFileSync|execFile|execSync|exec|fork)\s*\(/;

function insideString(line, i) {
  for (const q of ['"', "'", "`"]) {
    let n = 0;
    for (let k = 0; k < i; k++) if (line[k] === q && line[k - 1] !== "\\") n++;
    if (n % 2 === 1) return true;
  }
  return false;
}

function requireClosure(root, files) {
  const set = new Set(files);
  const unresolved = [];
  const resolveIn = (fromRel, spec) => {
    const base = path.posix.normalize(path.posix.join(path.posix.dirname(fromRel), spec));
    for (const c of [base, `${base}.js`, `${base}.json`, `${base}.mjs`, `${base}.cjs`, `${base}/index.js`]) if (set.has(c) || OPTIONAL_PRIVATE[c]) return c;
    return null;
  };
  for (const f of files.filter((x) => /\.(?:c?m?js)$/.test(x) && !NOT_SCRIPT_SCOPE_RE.test(x))) {
    let src;
    try { src = fs.readFileSync(path.join(root, f), "utf8"); } catch { continue; }
    src = src.replace(/\/\*[\s\S]*?\*\//g, "");
    for (const raw of src.split("\n")) {
      const line = raw.replace(/(^|[^:"'`\\])\/\/[^\n]*$/, "$1");
      for (const m of line.matchAll(/require\(\s*(["'])(\.\.?\/[^"']+)\1\s*\)/g)) {
        if (insideString(line, m.index)) continue;
        if (!resolveIn(f, m[2])) unresolved.push({ source: f, kind: "require", entry: m[2] });
      }
      if (!SPAWN_CALL_RE.test(line)) continue;
      for (const m of line.matchAll(/(["'`])(scripts\/[A-Za-z0-9_./-]+\.(?:c?m?js|sh))\1/g)) {
        if (!set.has(m[2]) && !OPTIONAL_PRIVATE[m[2]]) unresolved.push({ source: f, kind: "spawn", entry: m[2] });
      }
    }
  }
  return unresolved;
}

class RunnerError extends Error {}

function trackedFiles(root) {
  const r = spawnSync("git", ["-C", root, "ls-files", "-z"], { encoding: "utf8", maxBuffer: 1 << 28 });
  if (r.status !== 0) throw new RunnerError(`git ls-files failed at ${root}`);
  return r.stdout.split("\0").filter(Boolean);
}

function constLiteral(src, name) {
  const m = new RegExp(`(?:^|\\n)\\s*(?:const|let|var)\\s+${name}\\s*=\\s*`).exec(src);
  if (!m) return null;
  let i = m.index + m[0].length;
  const start = i;
  let depth = 0;
  for (; i < src.length; i++) {
    const c = src[i];
    if (c === '"' || c === "'" || c === "`") {
      for (i++; i < src.length && src[i] !== c; i++) if (src[i] === "\\") i++;
      continue;
    }
    if (c === "/" && src[i + 1] === "/") { while (i < src.length && src[i] !== "\n") i++; continue; }
    if (c === "/" && src[i + 1] === "*") { i = src.indexOf("*/", i + 2); if (i < 0) return null; i++; continue; }
    if (c === "(" || c === "[" || c === "{") depth++;
    else if (c === ")" || c === "]" || c === "}") { depth--; if (depth === 0) return src.slice(start, i + 1); }
    else if (c === ";" && depth === 0) return src.slice(start, i);
  }
  return null;
}

function codeEntries(literal, mode, kind) {
  const strip = literal.replace(/\/\/[^\n]*|\/\*[\s\S]*?\*\//g, "");
  const out = [];
  if (mode === "fields") {
    for (const m of strip.matchAll(/\b(?:prefix|path|file)\s*:\s*"([^"]*)"/g)) out.push([kind, m[1]]);
    for (const m of strip.matchAll(/\bmatch\s*:\s*([^,\n]*)/g)) {
      const re = /^\(?\s*\w+\s*\)?\s*=>\s*\/((?:\\.|\[(?:\\.|[^\]\\\n])*\]|[^/\\\n[])+)\/([a-z]*)\.test\(\s*\w+\s*\)$/.exec(m[1].trim());
      out.push(re ? ["regex", `/${re[1]}/${re[2]}`] : ["unverifiable", `predicate ${m[1].trim().slice(0, 60)}`]);
    }
  } else if (mode === "objectKeys") {
    for (const m of strip.matchAll(/(?:^|[{,\n])\s*"([^"]+)"\s*:/g)) out.push([kind, m[1]]);
  } else if (mode === "strings") {
    for (const m of strip.matchAll(/"([^"]+)"/g)) out.push([kind, m[1]]);
  } else if (mode === "mapKeys") {
    for (const m of strip.matchAll(/\[\s*"([^"]+)"\s*,/g)) out.push([kind, m[1]]);
  }
  return out;
}

function globRe(g) {
  const s = g.replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\*\*\/?|\*/g, (t) => (t === "*" ? "[^/]*" : "(?:.*/)?"));
  return new RegExp(`^${s}$`);
}

function makeResolver(root, files, runtimeUsed) {
  const set = new Set(files);
  const runtimeOk = (source, v) => {
    const r = (RUNTIME_PATHS[source] || {})[v];
    if (!r || !set.has(r.writer)) return false;
    if (r.named !== false && !fs.readFileSync(path.join(root, r.writer), "utf8").includes(v.replace(/\/$/, ""))) return false;
    runtimeUsed.add(`${source}\0${v}`);
    return true;
  };
  const readJson = (rel) => {
    try { return JSON.parse(fs.readFileSync(path.join(root, rel), "utf8").replace(/^﻿/, "")); } catch { return null; }
  };
  let roles, events;
  return (source, kind, v) => {
    if (typeof v !== "string" || !v) return false;
    if (kind === "file") return set.has(v) || (v.endsWith("/") && files.some((f) => f.startsWith(v))) || runtimeOk(source, v);
    if (kind === "prefix") return files.some((f) => f === v || f.startsWith(v)) || runtimeOk(source, v);
    if (kind === "substring") return files.some((f) => f.includes(v)) || runtimeOk(source, v);
    if (kind === "glob") { const re = globRe(v); return files.some((f) => re.test(f)); }
    if (kind === "regex") {
      const m = /^\/(.*)\/([a-z]*)$/s.exec(v);
      let re;
      try { re = new RegExp(m[1], m[2]); } catch { return false; }
      return files.some((f) => re.test(f));
    }
    if (kind === "role") {
      if (!roles) { const j = readJson(".claude/agents/_org/role-registry.json"); roles = new Set(objectEntries(j && j.roles)); }
      return roles.has(v);
    }
    if (kind === "event") {
      if (!events) { const j = readJson(".claude/agents/_org/mode-lifecycle-hooks.json"); events = new Set(arr(j && j.events).map((e) => e && e.event)); }
      return events.has(v);
    }
    return false;
  };
}

const LOCAL_FILE = path.join(".claude", "project", "memory", "config-path-resolves.local.json");
function localDataSources(root) {
  let raw;
  try {
    raw = fs.readFileSync(path.join(root, LOCAL_FILE), "utf8").replace(/^\uFEFF/, "");
  } catch (e) {
    if (e && e.code === "ENOENT") return null;
    throw new RunnerError(`unreadable instance-local file ${LOCAL_FILE}`);
  }
  let j;
  try { j = JSON.parse(raw); } catch { j = null; }
  const ds = j && j.dataSources;
  if (!ds || typeof ds !== "object" || Array.isArray(ds) || !Object.values(ds).every((r) => typeof r === "string" && r)) {
    throw new RunnerError(`malformed instance-local file ${LOCAL_FILE} (expected { "dataSources": { "<path>": "<reason>" } })`);
  }
  return Object.fromEntries(Object.entries(ds).map(([p, why]) => [p, { noPaths: `instance-local: ${why}` }]));
}

function run({ root, dataSources = DATA_SOURCES, codeSources = CODE_SOURCES } = {}) {
  const files = trackedFiles(root);
  const runtimeUsed = new Set();
  const resolves = makeResolver(root, files, runtimeUsed);
  const dangling = [], unverifiable = [], sources = [], skipped = [];
  let checked = 0;
  const judge = (source, kind, value) => {
    if (kind === "unverifiable") { unverifiable.push({ source, entry: value }); return; }
    checked++;
    if (!resolves(source, kind, value)) dangling.push({ source, kind, entry: value });
    else if ((RUNTIME_PATHS[source] || {})[value]) runtimeUsed.add(`${source}\0${value}`);
  };
  const local = localDataSources(root);
  if (local) dataSources = { ...dataSources, ...local };
  for (const rel of files.filter((f) => LIST_FILE_RE.test(path.posix.basename(f)) && !NOT_CONFIG_RE.test(f))) {
    const reg = dataSources[rel];
    if (!reg) throw new RunnerError(`unregistered allowlist-bearing file: ${rel} (register it in ${NAME}.js DATA_SOURCES)`);
    if (reg.noPaths) { skipped.push({ source: rel, reason: reg.noPaths }); continue; }
    let raw;
    try { raw = fs.readFileSync(path.join(root, rel), "utf8").replace(/^﻿/, ""); } catch { throw new RunnerError(`unreadable allowlist: ${rel}`); }
    let parsed;
    if (reg.text) parsed = raw.split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));
    else { try { parsed = JSON.parse(raw); } catch { throw new RunnerError(`malformed allowlist JSON: ${rel}`); } }
    sources.push(rel);
    for (const [kind, value] of reg.entries(parsed)) judge(rel, kind, value);
  }
  for (const cs of codeSources) {
    if (!files.includes(cs.file)) { skipped.push({ source: `${cs.file}#${cs.name}`, reason: "source file not in this tree" }); continue; }
    const src = fs.readFileSync(path.join(root, cs.file), "utf8");
    const lit = constLiteral(src, cs.name);
    if (lit == null) throw new RunnerError(`registered constant ${cs.name} not found in ${cs.file} (update ${NAME}.js CODE_SOURCES)`);
    sources.push(`${cs.file}#${cs.name}`);
    for (const [kind, value] of codeEntries(lit, cs.mode, cs.kind)) judge(`${cs.file}#${cs.name}`, kind, value);
  }
  const staleRuntime = Object.entries(RUNTIME_PATHS)
    .filter(([source]) => sources.includes(source))
    .flatMap(([source, m]) => Object.keys(m).filter((k) => !runtimeUsed.has(`${source}\0${k}`)).map((k) => `${source}: ${k}`));
  const unresolvedRequires = requireClosure(root, files);
  return { dangling, unverifiable, staleRuntime, unresolvedRequires, checked, sources, skipped };
}

function main(argv) {
  const ri = argv.indexOf("--root");
  const root = path.resolve(ri >= 0 && argv[ri + 1] ? argv[ri + 1] : path.resolve(__dirname, "..", ".."));
  const json = argv.includes("--json");
  let r;
  try {
    r = run({ root });
  } catch (e) {
    const msg = e instanceof RunnerError ? e.message : `runner crashed: ${e && e.message}`;
    if (json) console.log(JSON.stringify({ ok: false, code: 2, error: msg }));
    else console.error(`${NAME}: ERROR — ${msg}`);
    return 2;
  }
  const ok = r.dangling.length === 0 && r.unverifiable.length === 0 && r.staleRuntime.length === 0 && r.unresolvedRequires.length === 0;
  if (json) console.log(JSON.stringify({ ok, code: ok ? 0 : 1, ...r }, null, 2));
  else {
    console.log(`${NAME}: ${r.checked} entr${r.checked === 1 ? "y" : "ies"} in ${r.sources.length} source(s) checked at ${root}`);
    for (const d of r.dangling) console.log(`  DANGLING  ${d.source}: ${d.kind} '${d.entry}' does not resolve in this tree`);
    for (const u of r.unverifiable) console.log(`  UNVERIFIABLE  ${u.source}: ${u.entry} (rewrite it as a path, prefix, glob or a one-regex predicate)`);
    for (const k of r.staleRuntime) console.log(`  STALE-RUNTIME  RUNTIME_PATHS ${k} vouches for no entry, or its writer is gone or no longer names it`);
    for (const u of r.unresolvedRequires) console.log(`  UNRESOLVED-${u.kind.toUpperCase()}  ${u.source} -> ${u.entry} is not in this tree`);
    console.log(`  result: ${ok ? "OK" : "FAIL"} (exit ${ok ? 0 : 1})`);
  }
  return ok ? 0 : 1;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

