// ── helpers ──────────────────────────────────────────────────────────────────────────────────────────────────────────

/** Occupancy form of the token occurrence at index i of text — a SUB-COUNT only, never a verdict input. */
function occupancyForm(text, i) {
  const hasOs = /^os/i.test(text.slice(i + 4, i + 6));
  const end = i + 4 + (hasOs ? 2 : 0);
  const word = text.slice(i, end);
  const before = i > 0 ? text[i - 1] : "";
  const after = end < text.length ? text[end] : "";
  const after2 = end + 1 < text.length ? text[end + 1] : "";
  if (after === "@") return "tag-token";
  if (after === ":" && /[A-Za-z]/.test(after2)) return "command-namespace";
  if (word === word.toUpperCase() && after === "_") return "env-name";
  if (before === "/" || after === "/" || before === "\\" || after === "\\") return "path-segment";
  if (after === "-" || before === "-") return "hyphen-name";
  if (/[A-Za-z0-9_$]/.test(before) || /[A-Za-z0-9_$]/.test(after)) return "identifier";
  return "word";
}

function tokenIndexes(text) {
  const out = [];
  const re = TOKEN_RE();
  let m;
  while ((m = re.exec(text)) !== null) out.push(m.index);
  return out;
}

/** Heading-scoped history line set for a tracker file. */
function trackerHistoryLines(content) {
  const set = new Set();
  let openLevel = null;
  content.split(/\r?\n/).forEach((lineText, idx) => {
    const h = /^(#{1,6})\s+(.*?)\s*$/.exec(lineText);
    if (h) {
      const level = h[1].length;
      const title = h[2].replace(/[`*_]/g, "").trim().toLowerCase();
      if (openLevel !== null && level <= openLevel) openLevel = null;
      if (openLevel === null && TRACKER_HISTORY_HEADINGS.includes(title)) openLevel = level;
    }
    if (openLevel !== null) set.add(idx + 1);
  });
  return set;
}

/** Spans [start,end) of tag tokens on a line that the tag rule admits. */
function admittedTagSpans(lineText, tagVersions) {
  const spans = [];
  const re = new RegExp(`${SLUG}@(<semver>|\\*|[0-9A-Za-z._+-]+)`, "g"); // case-SENSITIVE: the tag spelling
  let m;
  while ((m = re.exec(lineText)) !== null) {
    let v = m[1];
    const kind = v === "<semver>" || v === "*" ? "class-reference" : "existing-tag";
    if (kind === "existing-tag") {
      v = v.replace(/[.]+$/, "");
      if (!tagVersions.has(v)) continue;
    }
    spans.push({ start: m.index, end: m.index + SLUG.length + 1 + v.length, kind });
  }
  return spans;
}

function inSpans(spans, i) {
  return spans.find((s) => i >= s.start && i < s.end) || null;
}

function listTagVersions(root) {
  const r = L.git(root, ["tag", "-l", `${SLUG}@*`]);
  if (r.status !== 0) throw new L.OracleRefusal(`git tag -l failed: ${(r.stderr || "").trim()}`);
  const tags = r.stdout.split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
  return { count: tags.length, versions: new Set(tags.map((t) => t.slice(SLUG.length + 1))) };
}

// ── classification ───────────────────────────────────────────────────────────────────────────────────────────────────

function makeClassifier({ partition, loader, treeVersion }) {
  const cache = new Map();
  const unclassifiable = [];
  function classifyFile(rel) {
    if (cache.has(rel)) return cache.get(rel);
    let pc;
    try {
      pc = partition.classifyPath(rel);
    } catch (e) {
      pc = null;
      unclassifiable.push(`${rel} (classifyPath threw: ${e.message})`);
    }
    if (pc && !loader.VALID_CLASSES.includes(pc.class)) {
      unclassifiable.push(`${rel} (partition class ${JSON.stringify(pc.class)} is not one of ${loader.VALID_CLASSES.join("/")})`);
      pc = null;
    }
    const hits = PATH_RULES.filter((r) => r.test(rel));
    let c;
    if (!pc) {
      c = { kind: "unclassifiable" };
    } else if (hits.length > 1) {
      unclassifiable.push(`${rel} (ambiguous: section 1 path rules ${hits.map((h) => h.id).join(" + ")})`);
      c = { kind: "unclassifiable" };
    } else if (hits.length === 1 && pc.kind === "compat") {
      unclassifiable.push(`${rel} (holds two: section 1 rule ${hits[0].id} AND compat member of ${pc.entry.surface})`);
      c = { kind: "unclassifiable" };
    } else if (hits.length === 1) {
      c = { kind: "historical", rule: hits[0].id, pc };
    } else if (pc.kind === "compat") {
      c = loader.isCompatExpired(pc.entry.expires, treeVersion)
        ? { kind: "live", sub: `compat-expired:${pc.entry.surface}(expires ${pc.entry.expires})`, pc }
        : { kind: "compat", surface: pc.entry.surface, expires: pc.entry.expires, pc };
    } else if (pc.kind === "generated-view") {
      c = { kind: "live", sub: "generated-view", view: true, pc };
    } else if (pc.class !== 1) {
      c = { kind: "live", contested: true, sub: `CONTESTED partition class-${pc.class} ${pc.kind} '${pc.entry && pc.entry.pattern}' (no section 1 row)`, pc };
    } else {
      c = { kind: "live", sub: "class-1 default", pc };
    }
    cache.set(rel, c);
    return c;
  }
  const covered = (c) => c.kind === "historical" || c.kind === "compat";
  return { classifyFile, covered, unclassifiable };
}

// ── derived-view attribution ─────────────────────────────────────────────────────────────────────────────────────────

function analyzeView(rel, content, ctx) {
  const { trackedSet, dirSet, pathCoverage } = ctx;
  const raw = tokenIndexes(content).length;
  const rows = [];
  let attributed = 0;
  const bySource = {};
  let parsed;
  try {
    parsed = JSON.parse(content.replace(/^﻿/, ""));
  } catch {
    if (raw) {
      rows.push({ view: rel, string: "(view is not JSON)", n: raw, source: null, sourceClass: "unattributable" });
      L.bump(bySource, "unattributable(non-JSON view)", raw);
    }
    return { raw, attributed: raw, rows, bySource, coveredN: 0 };
  }
  let coveredN = 0;
  const isTokenPath = (s) => (trackedSet.has(s) || dirSet.has(s.replace(/\/+$/, ""))) && TOKEN_RE().test(s);
  const handle = (s, ctxStrings) => {
    const n = tokenIndexes(s).length;
    if (!n) return;
    attributed += n;
    const self = s.trim();
    let cands = isTokenPath(self) ? [self] : [...new Set(ctxStrings)].filter((x) => typeof x === "string" && isTokenPath(x.trim())).map((x) => x.trim());
    if (!cands.length) {
      rows.push({ view: rel, string: s.slice(0, 160), n, source: null, sourceClass: "unattributed" });
      L.bump(bySource, "unattributed", n);
      return;
    }
    const liveCand = cands.find((x) => !pathCoverage(x).covered);
    if (liveCand) {
      const cov = pathCoverage(liveCand);
      rows.push({ view: rel, string: s.slice(0, 160), n, source: liveCand, sourceClass: `live-source:${cov.label}` });
      L.bump(bySource, `live-source:${cov.label}`, n);
    } else {
      coveredN += n;
      L.bump(bySource, `covered-source:${pathCoverage(cands[0]).label}`, n);
    }
  };
  const walk = (node, parentCtx) => {
    if (Array.isArray(node)) {
      for (const child of node) walk(child, parentCtx);
      return;
    }
    if (!node || typeof node !== "object") return;
    const shallow = [...Object.keys(node), ...Object.values(node).filter((v) => typeof v === "string")];
    for (const [k, v] of Object.entries(node)) {
      const childShallow = v && typeof v === "object" && !Array.isArray(v) ? [...Object.keys(v), ...Object.values(v).filter((x) => typeof x === "string")] : [];
      handle(k, [...shallow, ...childShallow, ...parentCtx]);
      if (typeof v === "string") handle(v, [...shallow, ...parentCtx]);
      else if (v && typeof v === "object") walk(v, [k, ...shallow.filter((x) => typeof x === "string")]);
    }
  };
  walk(parsed, []);
  if (attributed !== raw) {
    const gap = Math.abs(raw - attributed);
    rows.push({ view: rel, string: `(raw ${raw} != parsed ${attributed})`, n: gap, source: null, sourceClass: "unattributed(parse-gap)" });
    L.bump(bySource, "unattributed(parse-gap)", gap);
  }
  return { raw, attributed, rows, bySource, coveredN };
}

// ── measure ──────────────────────────────────────────────────────────────────────────────────────────────────────────

function measure({ root = L.REPO_ROOT, keepRegen = false, regenFn = regenerateViews } = {}) {
  const head = L.measuredHead(root);
  const loader = L.loadLoader(root);
  const codemod = L.loadCodemod(root);
  const partition = loader.loadPartition({ forceReload: true });
  const tracked = L.listTracked(root);
  const trackedSet = new Set(tracked);
  const tv = loader.readTreeVersion(root);
  if (!tv.version) throw new L.OracleRefusal(`tree version unreadable: ${tv.reason} — compat expiry cannot be evaluated`);
  const tags = listTagVersions(root);
  if (tags.count === 0) throw new L.OracleRefusal(`no local ${SLUG}@* tags — the section 1 tag class cannot be evaluated (fail closed)`);

  const K = makeClassifier({ partition, loader, treeVersion: tv.version });

  // distinct path set (files + ancestor directories)
  const dirSet = new Set();
  for (const f of tracked) {
    const segs = f.split("/");
    for (let i = 1; i < segs.length; i++) dirSet.add(segs.slice(0, i).join("/"));
  }
  const filesBeneath = new Map();
  for (const f of tracked) {
    const segs = f.split("/");
    for (let i = 1; i < segs.length; i++) {
      const d = segs.slice(0, i).join("/");
      if (!filesBeneath.has(d)) filesBeneath.set(d, []);
      filesBeneath.get(d).push(f);
    }
  }

  /** Coverage of a tracked PATH (file or directory) at name grain. */
  const pathCoverage = (p) => {
    if (trackedSet.has(p)) {
      const c = K.classifyFile(p);
      if (c.kind === "historical") return { covered: true, label: `historical:${c.rule}` };
      if (c.kind === "compat") return { covered: true, label: `compat:${c.surface}(expires ${c.expires})` };
      return { covered: false, label: c.kind === "unclassifiable" ? "unclassifiable" : `live:${c.sub}`, contested: !!c.contested };
    }
    const beneath = filesBeneath.get(p) || [];
    const liveFiles = beneath.filter((f) => {
      const c = K.classifyFile(f);
      return !K.covered(c);
    });
    if (beneath.length && liveFiles.length === 0) {
      const labels = [...new Set(beneath.map((f) => pathCoverage(f).label))];
      return { covered: true, label: `dir-all-members-covered{${labels.join(", ")}}` };
    }
    const contested = liveFiles.length > 0 && liveFiles.every((f) => K.classifyFile(f).contested);
    return {
      covered: false,
      label: `live-dir(${liveFiles.length} of ${beneath.length} files beneath are live${contested ? ", all CONTESTED" : ""})`,
      contested,
      liveBeneath: liveFiles.length,
    };
  };

  const regen = regenFn({ root, sha: head.sha, partition, trackedFiles: tracked, version: tv.version, keep: keepRegen });

  // ── CONTENT grain ──
  const pop = L.newPopulation("oracle (iv) CONTENT grain — every tracked file");
  pop.rules.scanned =
    "text file read and swept at occurrence grain — EVERY class (historical, compat, live, contested); generated views read from REGENERATED bytes; write-protected files swept";
  pop.rules.binary = L.RULE_TEXT.binary + " — its NAME is still swept at name grain";
  pop.rules.unreadable = L.RULE_TEXT.unreadable;
  pop.rules.oversized = L.RULE_TEXT.oversized;
  pop.rules.generated = "NONE excluded by (iv): each generated view is swept on regenerated bytes and attributed to its source path — counted under scanned{live:generated-view}";
  pop.rules["write-protected"] = "NONE excluded by (iv): the partition's writeProtected flag is not a section 1 class — write-protected files are swept and classified like any other";

  const covered = {}; // rule id -> occurrences
  const coveredSub = {};
  const violationsBySub = {};
  const violationsByForm = {};
  const violationsByFile = {};
  const formsAll = {};
  const contentViolations = [];
  let occurrences = 0;
  let contestedContent = 0;
  const derived = { raw: 0, attributed: 0, covered: 0, rows: [], bySource: {} };
  const readmeBrandLines = { count: 0, line: null };

  for (const rel of tracked) {
    pop.eligible += 1;
    const c = K.classifyFile(rel);
    const isView = partition.isGeneratedView(rel);
    const override = isView ? regen.views.get(rel) : undefined;
    if (isView && override === undefined) throw new L.OracleRefusal(`generated view ${rel} has no regenerated bytes — refusing to sweep stale bytes`);
    const r = L.readForScan(path.join(root, rel), codemod, override);
    const subLabel = c.kind === "historical" ? `historical:${c.rule}` : c.kind === "compat" ? `compat:${c.surface}` : c.kind === "live" ? (c.contested ? "live:CONTESTED" : `live:${c.sub}`) : "unclassifiable";
    if (r.status !== "text") {
      L.popAdd(pop, r.status, subLabel);
      if (r.status === "unreadable") pop.unreadableFiles.push(rel);
      if (r.status === "oversized") pop.oversizedFiles.push(rel);
      continue;
    }
    L.popAdd(pop, "scanned", subLabel);
    const content = r.content;
    const all = tokenIndexes(content);
    if (rel === BRAND_FILE) {
      const bl = content.split(/\r?\n/).map((t, i) => [t, i + 1]).filter(([t]) => t.includes(BRAND_PHRASE));
      readmeBrandLines.count = bl.length;
      readmeBrandLines.line = bl.length === 1 ? bl[0][1] : null;
    }
    if (all.length === 0) continue;
    occurrences += all.length;
    if (c.kind === "unclassifiable") continue; // counted; the run refuses below

    if (c.kind === "historical" || c.kind === "compat") {
      const key = c.kind === "historical" ? c.rule : `H1-compat:${c.surface}(expires ${c.expires}) member`;
      L.bump(covered, c.kind === "historical" ? c.rule : "H1-compat", all.length);
      L.bump(coveredSub, key, all.length);
      for (const i of all) L.bump(formsAll, occupancyForm(content, i));
      continue;
    }

    if (isView) {
      const a = analyzeView(rel, content, { trackedSet, dirSet, pathCoverage });
      derived.raw += a.raw;
      derived.attributed += a.attributed;
      derived.covered += a.coveredN;
      for (const [k, v] of Object.entries(a.bySource)) L.bump(derived.bySource, k, v);
      for (const row of a.rows) derived.rows.push(row);
      if (a.coveredN) {
        L.bump(covered, "H1-derived-from-covered-source", a.coveredN);
        L.bump(coveredSub, `derived:view ${rel} (source covered)`, a.coveredN);
      }
      continue;
    }

    // live file (default class-1, contested, or expired compat member): occurrence grain
    const lines = content.split(/\r?\n/);
    const clHist = rel === CHANGELOG_FILE ? loader.historicalChangelogLines(content) : null;
    const trHist = TRACKER_FILE_RE.test(rel) ? trackerHistoryLines(content) : null;
    lines.forEach((lineText, idx) => {
      const lineNum = idx + 1;
      const idxs = tokenIndexes(lineText);
      if (!idxs.length) return;
      const tagSpans = admittedTagSpans(lineText, tags.versions);
      let brandSpans = [];
      if (rel === BRAND_FILE && readmeBrandLines.count === 1 && lineText.includes(BRAND_PHRASE)) {
        let from = 0;
        let j;
        while ((j = lineText.indexOf(BRAND_PHRASE, from)) !== -1) {
          brandSpans.push({ start: j, end: j + BRAND_PHRASE.length });
          from = j + BRAND_PHRASE.length;
        }
      }
      const compatOccs = compatOccurrenceSpans(partition, loader, rel, lineText, tv.version);
      for (const i of idxs) {
        const form = occupancyForm(lineText, i);
        L.bump(formsAll, form);
        const tag = inSpans(tagSpans, i);
        if (tag) {
          L.bump(covered, "H1-tags");
          L.bump(coveredSub, `H1-tags:${tag.kind}`);
          continue;
        }
        if (inSpans(brandSpans, i)) {
          L.bump(covered, "H1-brand-line");
          L.bump(coveredSub, `H1-brand-line:${rel}:${lineNum}`);
          continue;
        }
        const co = inSpans(compatOccs, i);
        if (co && !co.expired) {
          L.bump(covered, "H1-compat");
          L.bump(coveredSub, `H1-compat:${co.surface}(expires ${co.expires}) anchored occurrence`);
          continue;
        }
        if (clHist && clHist.has(lineNum)) {
          L.bump(covered, "H1-changelog-history");
          L.bump(coveredSub, "H1-changelog-history");
          continue;
        }
        if (trHist && trHist.has(lineNum)) {
          L.bump(covered, "H1-tracker-history");
          L.bump(coveredSub, `H1-tracker-history:${rel}`);
          continue;
        }
        const sub = co && co.expired ? `compat-expired:${co.surface}(expires ${co.expires}) anchored occurrence` : c.contested ? c.sub : `live:${c.sub}`;
        if (c.contested) contestedContent += 1;
        L.bump(violationsBySub, sub);
        L.bump(violationsByForm, form);
        L.bump(violationsByFile, rel);
        contentViolations.push({ file: rel, line: lineNum, col: i + 1, form, match: lineText.substr(i, /^os/i.test(lineText.slice(i + 4, i + 6)) ? 6 : 4), contested: !!c.contested, sub, text: lineText.trim().slice(0, 200) });
      }
    });
  }

  if (K.unclassifiable.length) {
    throw new L.OracleRefusal(`${K.unclassifiable.length} tracked path(s) cannot be LIVE-classified (first: ${K.unclassifiable.slice(0, 5).join("; ")}) — refusing rather than treating them as non-live`);
  }
  L.assertPopulation(pop);

  // derived rows that are violations
  const derivedViolations = derived.rows.filter((r) => !String(r.sourceClass).startsWith("covered"));
  const derivedViolationN = derivedViolations.reduce((a, r) => a + r.n, 0);
  const derivedContested = derivedViolations.filter((r) => /CONTESTED/.test(r.sourceClass)).reduce((a, r) => a + r.n, 0);
  if (derived.covered + derivedViolationN !== derived.raw) {
    throw new L.OracleRefusal(`derived arithmetic does not hold: raw ${derived.raw} != covered ${derived.covered} + violations ${derivedViolationN}`);
  }

  const coveredTotal = Object.values(covered).reduce((a, b) => a + b, 0);
  const contentViolationN = contentViolations.length;
  if (coveredTotal + contentViolationN + derivedViolationN !== occurrences) {
    throw new L.OracleRefusal(
      `occurrence arithmetic does not hold: occurrences ${occurrences} != covered ${coveredTotal} + content violations ${contentViolationN} + derived violations ${derivedViolationN} — an occurrence holds zero or two buckets`
    );
  }

  // ── NAME grain ──
  const allPaths = [...new Set([...tracked, ...dirSet])].sort();
  const namePop = L.newPopulation("oracle (iv) NAME grain — every distinct tracked path (files + ancestor directories)");
  for (const t of L.TERM_ORDER) namePop.rules[t] = "NONE — a path string is always readable; no name is excluded";
  namePop.rules.scanned = "the LAST segment of every distinct tracked path is swept for grammar T (a directory once, never once per file beneath it)";
  const nameCovered = {};
  const nameViolations = [];
  const nameFormsAll = {};
  let nameTokenOccurrences = 0;
  let namedPaths = 0;
  let filesBeneathNamedDirs = 0;
  for (const p of allPaths) {
    namePop.eligible += 1;
    const isFile = trackedSet.has(p);
    L.popAdd(namePop, "scanned", isFile ? "file" : "directory");
    const seg = p.slice(p.lastIndexOf("/") + 1);
    const idxs = tokenIndexes(seg);
    if (!idxs.length) continue;
    namedPaths += 1;
    nameTokenOccurrences += idxs.length;
    for (const i of idxs) L.bump(nameFormsAll, occupancyForm(seg, i));
    if (!isFile) filesBeneathNamedDirs += (filesBeneath.get(p) || []).length;
    const cov = pathCoverage(p);
    if (cov.covered) {
      L.bump(nameCovered, `${isFile ? "file" : "dir"} ${cov.label}`);
    } else {
      nameViolations.push({
        path: p,
        kind: isFile ? "file" : "directory",
        forms: [...new Set(idxs.map((i) => occupancyForm(seg, i)))],
        contested: !!cov.contested,
        sub: cov.label,
        filesBeneath: isFile ? null : (filesBeneath.get(p) || []).length,
      });
    }
  }
  if (K.unclassifiable.length) {
    throw new L.OracleRefusal(`${K.unclassifiable.length} tracked path(s) cannot be LIVE-classified at name grain (first: ${K.unclassifiable.slice(0, 5).join("; ")})`);
  }
  L.assertPopulation(namePop);
  const nameCoveredTotal = Object.values(nameCovered).reduce((a, b) => a + b, 0);
  if (nameCoveredTotal + nameViolations.length !== namedPaths) {
    throw new L.OracleRefusal(`name arithmetic does not hold: named paths ${namedPaths} != covered ${nameCoveredTotal} + violations ${nameViolations.length}`);
  }

  return {
    head,
    regen,
    treeVersion: tv,
    tags,
    readmeBrandLines,
    pop,
    namePop,
    occurrences,
    covered,
    coveredSub,
    coveredTotal,
    formsAll,
    contentViolations,
    contestedContent,
    violationsBySub,
    violationsByForm,
    violationsByFile,
    derived,
    derivedViolations,
    derivedViolationN,
    derivedContested,
    namedPaths,
    nameTokenOccurrences,
    filesBeneathNamedDirs,
    nameCovered,
    nameViolations,
    nameFormsAll,
  };
}

/** Anchored compat occurrence spans on a line (exact file, matchText + anchor), each with its window's expiry state. */
function compatOccurrenceSpans(partition, loader, rel, lineText, version) {
  const spans = [];
  for (const w of partition.compatWindows || []) {
    for (const o of Array.isArray(w && w.occurrences) ? w.occurrences : []) {
      if (!o || o.file !== rel || typeof o.matchText !== "string" || !o.matchText) continue;
      if (!lineText.includes(o.matchText)) continue;
      if (o.anchor && !lineText.includes(o.anchor)) continue;
      let from = 0;
      let j;
      while ((j = lineText.indexOf(o.matchText, from)) !== -1) {
        spans.push({ start: j, end: j + o.matchText.length, surface: w.surface, expires: w.expires, expired: loader.isCompatExpired(w.expires, version) });
        from = j + o.matchText.length;
      }
    }
  }
  return spans;
}

