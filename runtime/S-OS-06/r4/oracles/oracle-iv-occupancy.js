/**
 * ORACLE (iv) — legacy-token OCCUPANCY of LIVE surfaces (S-OS-06 r4, oracle-coverage-map.md "ORACLE (iv)").
 *
 * PROPERTY GUARANTEED. No LIVE surface contains a legacy-project token in any occupancy form — file or directory NAME,
 * path segment, command or skill namespace, environment-variable name, identifier in code, or prose word — except where
 * the occurrence is covered by a ratified HISTORICAL class from STOP-CONDITION.md section 1, or is a registered alias
 * shim carrying a per-entry EXPIRY in the compat register (the partition's compatWindows, read through its one loader).
 *
 * WHAT IS DIFFERENT FROM ORACLES (i)-(iii). Those are keyed to the legacy SLUG and to lab@version tokens. This oracle's
 * grammar T is the legacy ROOT token (the slug's first four letters) matched case-insensitively ANYWHERE — so the
 * command namespace (`<root>:promote`), the filename prefix (`<root>-setup.js`), env names and identifiers are inside
 * the population by construction, not by a surface-form list. Every occurrence counts; the occupancy FORM of each one
 * is emitted as a sub-count only and never decides a verdict.
 *
 * POPULATION — two grains, both emitted, counted separately:
 *   CONTENT  per occurrence, over every tracked file:
 *              eligible == scanned + binary + unreadable + oversized + generated + write-protected
 *            generated views are swept on REGENERATED bytes (throwaway clone, regen-views.js); write-protected files are
 *            swept (the partition's writeProtected is not a section 1 class). unreadable and oversized MUST be 0 or REFUSE.
 *   NAMES    per path, over every DISTINCT tracked path (each tracked file plus each of its ancestor directories), so a
 *            filename is an occurrence a content sweep cannot see, and a directory counts ONCE, not once per file beneath
 *            it (the per-file count beneath legacy-named directories is emitted beside it).
 *
 * LIVE CLASSIFICATION (fail-closed). A tracked file is HISTORICAL only by a section 1 row below; it is COMPAT only as an
 * unexpired registered compat member; otherwise it is LIVE. A path the partition allow-lists (class 2/3/4 path glob or
 * future entry) that NO section 1 row admits is LIVE and is emitted in its own CONTESTED sub-population, per entry, so
 * a ruling on it is measurable rather than invisible. The oracle REFUSES (exit 2) when a path cannot be classified:
 * the loader throws, classifyPath returns an invalid class, two section 1 path rules claim one path, or a section 1
 * path rule and a compat membership claim the same path. Nothing falls out of the population by a bare `continue`.
 *
 * EVERY PRINTED ZERO SHIPS ITS EMITTED SET AND ITS DENOMINATOR. The full violation set (and the per-rule covered
 * counts) is written with --emit; the frame names that file and the denominators beside every count.
 *
 * Exit: 0 measured, zero violations | 1 measured, violations | 2 REFUSED (no count is a result).
 *
 * Usage: node runtime/S-OS-06/r4/oracles/oracle-iv-occupancy.js [--out <frame.out>] [--emit <set.json>] [--keep-regen]
 *
 * Self-reference hygiene: the root token is assembled at runtime; this file lives under runtime/** (a section 1 class).
 */

