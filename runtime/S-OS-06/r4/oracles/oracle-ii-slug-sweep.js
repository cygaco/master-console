#!/usr/bin/env node
"use strict";

/**
 * ORACLE (ii) — case-insensitive, occurrence-grain legacy-slug sweep over the WHOLE tracked population, compat lines
 * INCLUDED. S-OS-06 r4 STAGE 1: a measurement instrument. It fixes nothing, writes no warrant, changes no codemod rule.
 *
 * Every needle occurrence (case-insensitive) in every tracked text file lands in EXACTLY ONE bucket:
 *
 *   FIVE dispositions (β-corrected grain; evidence-tag / brand-history are SUB-KINDS of pinned, not dispositions):
 *     rewritten                 Class-1 live, unprotected, and the codemod's four-form scoped rewrite removes it (pending)
 *     pinned                    pinned:occurrence-pin | pinned:evidence-tag | pinned:brand-history  (dispositionAt, Class-1)
 *                               pinned:class3-path (a Class-3 path-glob / future-entry file)
 *     derived                   an occurrence in a generated view, swept against REGENERATED bytes
 *     compat                    an unexpired registered compat window (member file or anchored occurrence)
 *     historical-allow-listed   historical-allow-listed:class4 | historical-allow-listed:class2-gated
 *
 *   UNREGISTERED ABSOLUTION (measured, not a disposition): changelog-historical — rename-mc.js:679 (delta) and :755
 *     (ledger) OR an inline `isChangelog && changelogHistoricalLines.has(lineNum)` boolean into protection. No register
 *     entry stands behind it; it is counted on its own line so stage 2 can register it or fold it into pinned.
 *
 *   RESIDUE (undispositioned — each is a violation):
 *     odd-case-unrewritable     an unprotected Class-1 occurrence whose case form the four-form rewriter does not map
 *     raw-legacy-env-read       an unprotected Class-1 occurrence on a line CATEGORY_TRANSFORMS refuses (null)
 *     uncomputable-category     categorizer threw / category has no registered transform
 *     compat-expired            a compat occurrence whose window expiry the tree version has reached
 *     class1-write-protected-non-view   a Class-1 write-protected file that is not a declared generated view
 *
 * Arithmetic asserted: occurrences == rewritten + pinned + derived + compat + historical-allow-listed + absolution + residue.
 * derived-without-pinned-source is asserted separately (a property of each derived occurrence's source path).
 *
 * Usage: node runtime/S-OS-06/r4/oracles/oracle-ii-slug-sweep.js [--out <file>] [--keep-regen]
 */

const path = require("path");
const L = require("./lib");
const { regenerateViews, formatRegen } = require("./regen-views");

const NAME = "oracle-ii";

function slugTest(s) {
  return new RegExp(L.SLUG, "i").test(s);
}

/** Name-level disposition of a tracked source path (the thing a derived occurrence is derived FROM). */
function sourceKind(partition, loader, p) {
  if (partition.isGeneratedView(p)) return "derived-view";
  const c = L.classify(partition, loader, p);
  if (!c) return "unclassified";
  if (c.kind === "compat") return "class-3:compat-member";
  if (c.class === 3) return "class-3:path";
  if (c.class === 4) return "class-4";
  if (c.class === 2) return "class-2";
  return c.writeProtected ? "class-1-write-protected" : "class-1-live";
}

const SOURCE_PRIORITY = ["class-3:path", "class-3:compat-member", "class-4", "class-2", "derived-view", "class-1-write-protected", "class-1-live", "unclassified"];
const STRICT_PINNED_SOURCES = new Set(["class-3:path", "class-3:compat-member"]);
const LENIENT_PINNED_SOURCES = new Set(["class-3:path", "class-3:compat-member", "class-4", "class-2"]);

/**
 * Attribute every needle occurrence in a regenerated JSON view to the tracked path it is derived from: the string
 * itself if it is a tracked path, else a tracked, slug-named path among the strings of its owning entry (the object
 * holding it, plus the key that names that object). Parse-count must equal the raw count; any gap is unattributed.
 */
function analyzeDerived(rel, content, ctx) {
  const { partition, loader, trackedSet } = ctx;
  const raw = (content.match(L.NEEDLE_ALL_RE()) || []).length;
  const bySource = {};
  const samples = [];
  let attributed = 0;
  let parsed;
  try {
    parsed = JSON.parse(content.replace(/^﻿/, ""));
  } catch {
    if (raw) bySource["no-source-computable (view is not JSON)"] = raw;
    return { raw, attributed: raw, bySource, samples };
  }
  const handle = (s, ctxStrings) => {
    const n = (s.match(L.NEEDLE_ALL_RE()) || []).length;
    if (!n) return;
    attributed += n;
    const cands = [...new Set([s, ...ctxStrings])].filter((x) => trackedSet.has(x) && slugTest(x));
    let best = "no-tracked-source";
    let bestPath = null;
    for (const kind of SOURCE_PRIORITY) {
      const hit = cands.find((x) => sourceKind(partition, loader, x) === kind);
      if (hit) {
        best = kind;
        bestPath = hit;
        break;
      }
    }
    L.bump(bySource, best, n);
    if (!STRICT_PINNED_SOURCES.has(best) && samples.length < 40) samples.push({ view: rel, string: s.slice(0, 120), source: bestPath, sourceKind: best, n });
  };
  const walk = (node, parentCtx) => {
    if (Array.isArray(node)) {
      for (const child of node) walk(child, parentCtx);
      return;
    }
    if (!node || typeof node !== "object") return;
    const shallow = [...Object.keys(node), ...Object.values(node).filter((v) => typeof v === "string")];
    for (const [k, v] of Object.entries(node)) {
      const childShallow = v && typeof v === "object" && !Array.isArray(v) ? [...Object.keys(v), ...Object.values(v).filter((x) => typeof x === "string")] : [];
      handle(k, [...shallow, ...childShallow, ...parentCtx]);
      if (typeof v === "string") handle(v, [...shallow, ...parentCtx]);
      else if (v && typeof v === "object") walk(v, [k]);
    }
  };
  walk(parsed, []);
  if (attributed !== raw) L.bump(bySource, `unattributed (raw ${raw} != parsed ${attributed})`, Math.abs(raw - attributed));
  return { raw, attributed, bySource, samples };
}

function measure({ root = L.REPO_ROOT, keepRegen = false, regenFn = regenerateViews } = {}) {
  const head = L.measuredHead(root);
  const loader = L.loadLoader(root);
  const codemod = L.loadCodemod(root);
  const partition = loader.loadPartition({ forceReload: true });
  const tracked = L.listTracked(root);
  const trackedSet = new Set(tracked);
  const treeVersion = loader.readTreeVersion(root);
  if (!treeVersion.version) throw new L.OracleRefusal(`tree version unreadable: ${treeVersion.reason}`);

  const regen = regenFn({ root, sha: head.sha, partition, trackedFiles: tracked, version: treeVersion.version, keep: keepRegen });

  const pop = L.newPopulation("oracle (ii) — every tracked file");
  pop.rules.scanned = "text file read and swept at occurrence grain — ALL classes; generated views read from REGENERATED bytes; Class-2/3/4 + compat members swept and dispositioned by their register entry";
  pop.rules.binary = L.RULE_TEXT.binary;
  pop.rules.unreadable = L.RULE_TEXT.unreadable;
  pop.rules.oversized = L.RULE_TEXT.oversized;
  pop.rules.generated = "NONE excluded by (ii): each generated view is swept (derived) against regenerated bytes — counted under scanned{generated-view(regenerated)}";
  pop.rules["write-protected"] = "NONE excluded by (ii): write-protected files are swept; their occurrences carry the protecting entry's disposition — counted under scanned{write-protected:*}";

  const D = {
    rewritten: {},
    pinned: {},
    derived: {},
    compat: {},
    "historical-allow-listed": {},
  };
  const absolution = { "changelog-historical": 0 };
  let changelogHistAlsoRegistered = 0;
  const residue = {
    "odd-case-unrewritable": 0,
    "raw-legacy-env-read": 0,
    "uncomputable-category": 0,
    "compat-expired": 0,
    "class1-write-protected-non-view": 0,
  };
  const residueSamples = [];
  const oddCaseByBucket = {};
  const compatLineByBucket = {};
  const unclassified = [];
  let occurrences = 0;
  const derivedAnalysis = { bySource: {}, samples: [], raw: 0, attributed: 0 };
  const residueByFile = {};

  const noteResidue = (bucket, rel, lineNum, col, matchText, lineText) => {
    residue[bucket] += 1;
    L.bump(residueByFile, rel);
    if (residueSamples.length < 60) residueSamples.push(`${rel}:${lineNum}:${col + 1} [${bucket}] "${matchText}" :: ${lineText.trim().slice(0, 140)}`);
  };

  for (const rel of tracked) {
    pop.eligible += 1;
    const cls = L.classify(partition, loader, rel);
    if (!cls) {
      unclassified.push(rel);
      // an unclassified path still needs a population term: it is swept as text below but counted, and the run refuses.
    }
    const isView = partition.isGeneratedView(rel);
    const override = isView ? regen.views.get(rel) : undefined;
    if (isView && override === undefined) throw new L.OracleRefusal(`generated view ${rel} has no regenerated bytes — refusing to sweep stale bytes`);
    const r = L.readForScan(path.join(root, rel), codemod, override);
    if (r.status !== "text") {
      L.popAdd(pop, r.status, cls ? `class-${cls.class}:${cls.kind}` : "unclassified");
      if (r.status === "unreadable") pop.unreadableFiles.push(rel);
      if (r.status === "oversized") pop.oversizedFiles.push(rel);
      continue;
    }
    const scannedSub = isView
      ? "generated-view(regenerated)"
      : !cls
        ? "unclassified"
        : cls.class !== 1 || cls.writeProtected
          ? `write-protected:class-${cls.class}:${cls.kind}`
          : "class-1-live";
    L.popAdd(pop, "scanned", scannedSub);
    const content = r.content;
    const fileCount = (content.match(L.NEEDLE_ALL_RE()) || []).length;
    if (fileCount === 0) continue;
    occurrences += fileCount;

    if (!cls) continue; // counted in occurrences; refusal below (unclassified != 0)

    if (isView) {
      L.bump(D.derived, `derived:view ${rel}`, fileCount);
      const a = analyzeDerived(rel, content, { partition, loader, trackedSet });
      derivedAnalysis.raw += a.raw;
      derivedAnalysis.attributed += a.attributed;
      for (const [k, v] of Object.entries(a.bySource)) L.bump(derivedAnalysis.bySource, k, v);
      for (const s of a.samples) if (derivedAnalysis.samples.length < 40) derivedAnalysis.samples.push(s);
      continue;
    }

    const lines = content.split(/\r?\n/);
    const isChangelog = rel === "CHANGELOG.md";
    const hist = isChangelog ? loader.historicalChangelogLines(content) : null;

    lines.forEach((lineText, idx) => {
      const lineNum = idx + 1;
      const re = L.NEEDLE_ALL_RE();
      let m;
      const onCompatLine = cls.class === 1 && !cls.writeProtected && partition.findCompatOccurrence(rel, lineText) !== null;
      while ((m = re.exec(lineText)) !== null) {
        const form = L.caseForm(m[0], codemod);
        let bucket;
        if (cls.kind === "compat") {
          if (loader.isCompatExpired(cls.entry.expires, treeVersion.version)) {
            bucket = "residue:compat-expired";
            noteResidue("compat-expired", rel, lineNum, m.index, m[0], lineText);
          } else {
            bucket = `compat:${cls.entry.surface}`;
            L.bump(D.compat, `compat:${cls.entry.surface} (member)`);
          }
        } else if (cls.class === 3) {
          bucket = "pinned:class3-path";
          L.bump(D.pinned, "pinned:class3-path");
        } else if (cls.class === 4) {
          bucket = "historical-allow-listed:class4";
          L.bump(D["historical-allow-listed"], "historical-allow-listed:class4");
        } else if (cls.class === 2) {
          bucket = "historical-allow-listed:class2-gated";
          L.bump(D["historical-allow-listed"], "historical-allow-listed:class2-gated");
        } else if (cls.writeProtected) {
          bucket = "residue:class1-write-protected-non-view";
          noteResidue("class1-write-protected-non-view", rel, lineNum, m.index, m[0], lineText);
        } else {
          const at = partition.dispositionAt(rel, lineText, m.index);
          const histLine = isChangelog && hist.has(lineNum);
          if (histLine && at) changelogHistAlsoRegistered += 1;
          if (at && at.kind === "compat") {
            if (loader.isCompatExpired(at.window.expires, treeVersion.version)) {
              bucket = "residue:compat-expired";
              noteResidue("compat-expired", rel, lineNum, m.index, m[0], lineText);
            } else {
              bucket = `compat:${at.window.surface}`;
              L.bump(D.compat, `compat:${at.window.surface} (occurrence)`);
            }
          } else if (at && at.kind === "pinned") {
            bucket = at.rule ? `pinned:${at.rule}` : "pinned:occurrence-pin";
            L.bump(D.pinned, bucket);
          } else if (histLine) {
            bucket = "absolution:changelog-historical";
            absolution["changelog-historical"] += 1;
          } else {
            let category;
            try {
              category = codemod.categorizeOccurrence(rel, lineText);
            } catch (e) {
              category = null;
            }
            const transform =
              category && codemod.OCCURRENCE_CATEGORIES.includes(category) && Object.prototype.hasOwnProperty.call(codemod.CATEGORY_TRANSFORMS, category)
                ? codemod.CATEGORY_TRANSFORMS[category]
                : null;
            if (typeof transform !== "function") {
              bucket = "residue:uncomputable-category";
              noteResidue("uncomputable-category", rel, lineNum, m.index, m[0], lineText);
            } else if (transform(lineText) === null) {
              bucket = "residue:raw-legacy-env-read";
              noteResidue("raw-legacy-env-read", rel, lineNum, m.index, m[0], lineText);
            } else if (form === "odd-case") {
              bucket = "residue:odd-case-unrewritable";
              noteResidue("odd-case-unrewritable", rel, lineNum, m.index, m[0], lineText);
            } else {
              bucket = `rewritten:${category}`;
              L.bump(D.rewritten, bucket);
            }
          }
        }
        if (form === "odd-case") L.bump(oddCaseByBucket, bucket);
        if (onCompatLine) L.bump(compatLineByBucket, bucket);
      }
    });
  }

  if (unclassified.length) {
    throw new L.OracleRefusal(`${unclassified.length} tracked path(s) are UNCLASSIFIED (first: ${unclassified.slice(0, 5).join(", ")}) — no disposition is computable`);
  }
  L.assertPopulation(pop);

  const sum = (o) => Object.values(o).reduce((a, b) => a + b, 0);
  const dispTotals = Object.fromEntries(Object.entries(D).map(([k, v]) => [k, sum(v)]));
  const absTotal = sum(absolution);
  const residueTotal = sum(residue);
  const bucketSum = sum(dispTotals) + absTotal + residueTotal;
  if (bucketSum !== occurrences) {
    throw new L.OracleRefusal(`occurrence arithmetic does not hold: occurrences=${occurrences} but buckets sum to ${bucketSum} — an occurrence holds zero or two buckets`);
  }

  const derivedWithoutStrict = Object.entries(derivedAnalysis.bySource).filter(([k]) => !STRICT_PINNED_SOURCES.has(k)).reduce((a, [, v]) => a + v, 0);
  const derivedWithoutLenient = Object.entries(derivedAnalysis.bySource).filter(([k]) => !LENIENT_PINNED_SOURCES.has(k)).reduce((a, [, v]) => a + v, 0);

  // committed occurrence register (rename-mc.occurrences.json), read through the loader's exported path constant
  let registerCounts = null;
  try {
    registerCounts = JSON.parse(require("fs").readFileSync(loader.COMMITTED_LEDGER_PATH, "utf8")).dispositionCounts;
  } catch (e) {
    registerCounts = { error: e.message };
  }
  // same scope as the register: Class-1 files (views included) + compat members
  const scopePinned = sum(Object.fromEntries(Object.entries(D.pinned).filter(([k]) => k !== "pinned:class3-path"))) + absTotal;
  const scopeCompat = dispTotals.compat + residue["compat-expired"];
  const scopeRewrittenLabelled = dispTotals.rewritten + residue["odd-case-unrewritable"] + residue["raw-legacy-env-read"] + residue["uncomputable-category"];

  return {
    head,
    regen,
    pop,
    treeVersion,
    occurrences,
    D,
    dispTotals,
    absolution,
    absTotal,
    changelogHistAlsoRegistered,
    residue,
    residueTotal,
    residueSamples,
    residueByFile,
    oddCaseByBucket,
    compatLineByBucket,
    derivedAnalysis,
    derivedWithoutStrict,
    derivedWithoutLenient,
    registerCounts,
    scope: { pinned: scopePinned, derived: dispTotals.derived + residue["class1-write-protected-non-view"], compat: scopeCompat, rewrittenLabelled: scopeRewrittenLabelled },
  };
}

function format(r) {
  const out = [];
  const needleDesc = `/${L.SLUG}/gi`;
  out.push(`ORACLE (ii) — case-insensitive occurrence-grain legacy-slug sweep, compat lines INCLUDED (S-OS-06 r4 STAGE 1, measurement only)`);
  out.push(`  measured head: ${r.head.sha} (${r.head.branch}); tracked tree clean; tree version ${r.treeVersion.version} (${r.treeVersion.reason})`);
  out.push(`  needle: ${needleDesc} (every case mix counted); occurrence = one non-overlapping needle match`);
  out.push(...formatRegen(r.regen));
  out.push(...L.formatPopulation(r.pop));
  out.push(`  OCCURRENCES SWEPT: ${r.occurrences} (over scanned=${r.pop.terms.scanned} files of eligible=${r.pop.eligible})`);
  out.push(`  DISPOSITIONS (5; each occurrence in exactly one bucket):`);
  for (const k of ["rewritten", "pinned", "derived", "compat", "historical-allow-listed"]) {
    out.push(`    ${k.padEnd(24)} ${String(r.dispTotals[k]).padStart(7)}`);
    for (const [sk, sv] of L.sortedEntries(r.D[k])) out.push(`      ${String(sv).padStart(7)}  ${sk}`);
  }
  out.push(`  UNREGISTERED ABSOLUTION (closed by an inline boolean, rename-mc.js:679 delta + :755 ledger — NOT a register artifact):`);
  out.push(`    changelog-historical     ${String(r.absolution["changelog-historical"]).padStart(7)}  occurrences on CHANGELOG.md <2.0.0 section lines with NO registered disposition (dispositionAt === null), absolved only by the boolean`);
  out.push(`      (+${r.changelogHistAlsoRegistered} occurrence(s) on those lines ALSO carry a registered disposition — the boolean is redundant for them; counted under pinned/compat above)`);
  out.push(`  RESIDUE (undispositioned — violations):`);
  for (const [k, v] of Object.entries(r.residue)) out.push(`    ${k.padEnd(34)} ${String(v).padStart(7)}`);
  out.push(`    residue total                      ${String(r.residueTotal).padStart(7)}`);
  out.push(
    `  ARITHMETIC: occurrences ${r.occurrences} == rewritten ${r.dispTotals.rewritten} + pinned ${r.dispTotals.pinned} + derived ${r.dispTotals.derived} + compat ${r.dispTotals.compat} + historical-allow-listed ${r.dispTotals["historical-allow-listed"]} + absolution ${r.absTotal} + residue ${r.residueTotal}  [holds=true]`
  );
  const oddTotal = Object.values(r.oddCaseByBucket).reduce((a, b) => a + b, 0);
  out.push(`  ODD-CASE MIX (case form outside the rewriter's four): total=${oddTotal} (any bucket); unprotected-unrewritable=${r.residue["odd-case-unrewritable"]} (MUST be 0)`);
  for (const [k, v] of L.sortedEntries(r.oddCaseByBucket)) out.push(`      ${String(v).padStart(7)}  ${k}`);
  const compatLineTotal = Object.values(r.compatLineByBucket).reduce((a, b) => a + b, 0);
  out.push(`  COMPAT-LINE OCCURRENCES (Class-1 lines findCompatOccurrence matches — the lines rename-mc.js:671 skips whole): total=${compatLineTotal}`);
  for (const [k, v] of L.sortedEntries(r.compatLineByBucket)) out.push(`      ${String(v).padStart(7)}  ${k}`);
  out.push(`  DERIVED SOURCE CHECK (regenerated views; each occurrence attributed to the tracked path it derives from):`);
  out.push(`    derived occurrences raw=${r.derivedAnalysis.raw} attributed=${r.derivedAnalysis.attributed}`);
  for (const [k, v] of L.sortedEntries(r.derivedAnalysis.bySource)) out.push(`      ${String(v).padStart(7)}  source ${k}`);
  out.push(`    derived-without-pinned-source (STRICT — warrant text "corresponds to a Class-3 pin": source not Class-3 path/compat member) = ${r.derivedWithoutStrict}  (MUST be 0)`);
  out.push(`    derived-without-pinned-source (lenient — source not Class-3/4/2) = ${r.derivedWithoutLenient}  (informational)`);
  for (const s of r.derivedAnalysis.samples.slice(0, 20)) out.push(`      e.g. ${s.view} :: "${s.string}" -> ${s.source || "(none)"} [${s.sourceKind}] x${s.n}`);
  out.push(`  REGISTER COMPARISON (committed scripts/open-source/rename-mc.occurrences.json dispositionCounts vs this sweep, same scope: Class-1 files + compat members):`);
  out.push(`    register: ${JSON.stringify(r.registerCounts)}`);
  out.push(
    `    sweep:    {"rewritten-labelled":${r.scope.rewrittenLabelled},"pinned(incl. changelog-historical absolution)":${r.scope.pinned},"derived":${r.scope.derived},"compat(incl. expired)":${r.scope.compat}}`
  );
  if (r.residueSamples.length) {
    out.push(`  RESIDUE SAMPLES (first ${r.residueSamples.length}):`);
    for (const s of r.residueSamples) out.push(`    ${s}`);
    out.push(`  RESIDUE BY FILE (top 25): ${L.sortedEntries(r.residueByFile).slice(0, 25).map(([k, v]) => `${k}=${v}`).join("; ")}`);
  }
  const violations = r.residueTotal + r.absTotal + r.derivedWithoutStrict;
  out.push(
    `  VERDICT: violations=${violations} = residue ${r.residueTotal} + unregistered-absolution ${r.absTotal} + derived-without-pinned-source(strict) ${r.derivedWithoutStrict} — over ${r.occurrences} occurrences in ${r.pop.terms.scanned} scanned files (eligible ${r.pop.eligible})`
  );
  return { lines: out, code: violations === 0 ? 0 : 1 };
}

if (require.main === module) {
  L.runCli(NAME, (args, lines) => {
    const r = measure({ keepRegen: args.includes("--keep-regen") });
    const f = format(r);
    lines.push(...f.lines);
    return { code: f.code };
  });
}

module.exports = { measure, format, analyzeDerived };
