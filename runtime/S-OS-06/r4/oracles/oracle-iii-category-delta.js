#!/usr/bin/env node
"use strict";

/**
 * ORACLE (iii) — the codemod's per-category structural delta, recomputed at OCCURRENCE grain over ALL lines of every
 * Class-1 live file, compat lines INCLUDED (no whole-line `!findCompatOccurrence` skip). S-OS-06 r4 STAGE 1:
 * measurement only — the codemod's own delta (rename-mc.js:671 predicate) is untouched and reported beside this one.
 *
 * Per category C the codemod owns (rename-mc.js OCCURRENCE_CATEGORIES):
 *     categorized(C) == pinned(C) + transformed(C) + delta(C)
 *   pinned       the occurrence is protected: partition.dispositionAt != null (occurrence pin / evidence-tag RULE /
 *                brand-history RULE / compat occurrence) OR the CHANGELOG-historical inline boolean (rename-mc.js:679),
 *                each emitted as its own sub-count so the boolean's share is visible
 *   transformed  unprotected, the line has a transform (CATEGORY_TRANSFORMS[C](line) !== null) and the occurrence's case
 *                form is one the four-form scoped rewrite maps (so --apply removes it)
 *   delta        unprotected and NOT removed: a raw legacy env read (transform null) or an odd-case mix the rewriter
 *                cannot map
 *   uncomputable categorizer threw / category has no registered transform (counted apart; must be 0)
 *
 * Population: eligible = every tracked file; the delta measures Class-1 LIVE files only, and every other file is
 * excluded by a STATED RULE in the reconciliation (generated views: content derived, regenerated not transformed;
 * write-protected: Class-2/3/4 path entries + compat members, never a codemod transform target).
 *
 * Usage: node runtime/S-OS-06/r4/oracles/oracle-iii-category-delta.js [--out <file>]
 */

const path = require("path");
const L = require("./lib");

const NAME = "oracle-iii";

function measure({ root = L.REPO_ROOT } = {}) {
  const head = L.measuredHead(root);
  const loader = L.loadLoader(root);
  const codemod = L.loadCodemod(root);
  const partition = loader.loadPartition({ forceReload: true });
  const tracked = L.listTracked(root);

  const pop = L.newPopulation("oracle (iii) — every tracked file");
  pop.rules.scanned = "Class-1, non-write-protected, non-generated text file: EVERY line measured at occurrence grain, compat lines included";
  pop.rules.binary = L.RULE_TEXT.binary + " (checked on Class-1 live files; protected files are excluded before content is read)";
  pop.rules.unreadable = L.RULE_TEXT.unreadable;
  pop.rules.oversized = L.RULE_TEXT.oversized;
  pop.rules.generated =
    "partition.isGeneratedView(path) — a declared generated view; its content is DERIVED (regenerated by its builder, never transformed by the codemod), so it has no transform to measure (rename-mc.js:671 !isGenerated)";
  pop.rules["write-protected"] =
    "classifyPath: class != 1 (Class-2/3/4 path-glob / future-entry / compat member) OR writeProtected — never a codemod content-transform target (rename-mc.js:566-576 class1Files + :671 !writeProtected)";

  const cats = {};
  for (const c of codemod.OCCURRENCE_CATEGORIES) cats[c] = { categorized: 0, pinned: 0, transformed: 0, delta: 0, pinnedBy: {} };
  const uncomputable = [];
  const deltaRows = [];
  const unclassified = [];
  const compatLine = { occurrences: 0, pinned: 0, transformed: 0, delta: 0, uncomputable: 0 };
  let changelogBooleanOnly = 0;

  for (const rel of tracked) {
    pop.eligible += 1;
    const cls = L.classify(partition, loader, rel);
    if (!cls) {
      unclassified.push(rel);
      L.popAdd(pop, "write-protected", "UNCLASSIFIED");
      continue;
    }
    if (partition.isGeneratedView(rel)) {
      L.popAdd(pop, "generated", `class-${cls.class}:generated-view`);
      continue;
    }
    if (cls.class !== 1 || cls.writeProtected) {
      L.popAdd(pop, "write-protected", `class-${cls.class}:${cls.kind}`);
      continue;
    }
    const r = L.readForScan(path.join(root, rel), codemod);
    if (r.status !== "text") {
      L.popAdd(pop, r.status, "class-1-live");
      if (r.status === "unreadable") pop.unreadableFiles.push(rel);
      if (r.status === "oversized") pop.oversizedFiles.push(rel);
      continue;
    }
    L.popAdd(pop, "scanned", "class-1-live");
    const content = r.content;
    if (!L.NEEDLE_ALL_RE().test(content)) continue;
    const isChangelog = rel === "CHANGELOG.md";
    const hist = isChangelog ? loader.historicalChangelogLines(content) : null;

    content.split(/\r?\n/).forEach((lineText, idx) => {
      const lineNum = idx + 1;
      if (!L.NEEDLE_ALL_RE().test(lineText)) return;
      const onCompatLine = partition.findCompatOccurrence(rel, lineText) !== null;
      let category;
      let threw = null;
      try {
        category = codemod.categorizeOccurrence(rel, lineText);
      } catch (e) {
        threw = e.message;
      }
      const hasT =
        !threw && codemod.OCCURRENCE_CATEGORIES.includes(category) && Object.prototype.hasOwnProperty.call(codemod.CATEGORY_TRANSFORMS, category) && typeof codemod.CATEGORY_TRANSFORMS[category] === "function";
      const transformNull = hasT ? codemod.CATEGORY_TRANSFORMS[category](lineText) === null : null;
      const re = L.NEEDLE_ALL_RE();
      let m;
      while ((m = re.exec(lineText)) !== null) {
        if (onCompatLine) compatLine.occurrences += 1;
        if (!hasT) {
          uncomputable.push({ file: rel, line: lineNum, category: threw ? `<categorizer threw: ${threw}>` : String(category) });
          if (onCompatLine) compatLine.uncomputable += 1;
          continue;
        }
        const slot = cats[category];
        slot.categorized += 1;
        const at = partition.dispositionAt(rel, lineText, m.index);
        const histLine = isChangelog && hist.has(lineNum);
        if (at || histLine) {
          slot.pinned += 1;
          const by = at ? (at.kind === "compat" ? `compat:${at.window.surface}` : at.rule ? at.rule : "occurrence-pin") : "changelog-historical(inline boolean)";
          L.bump(slot.pinnedBy, by);
          if (!at && histLine) changelogBooleanOnly += 1;
          if (onCompatLine) compatLine.pinned += 1;
          continue;
        }
        const form = L.caseForm(m[0], codemod);
        if (transformNull || form === "odd-case") {
          slot.delta += 1;
          if (onCompatLine) compatLine.delta += 1;
          deltaRows.push({
            file: rel,
            line: lineNum,
            col: m.index + 1,
            category,
            reason: transformNull ? "raw-legacy-env-read (transform null)" : "odd-case (four-form rewriter does not map it)",
            matchText: m[0],
            onCompatLine,
            text: lineText.trim().slice(0, 140),
          });
        } else {
          slot.transformed += 1;
          if (onCompatLine) compatLine.transformed += 1;
        }
      }
    });
  }

  if (unclassified.length) {
    throw new L.OracleRefusal(`${unclassified.length} tracked path(s) are UNCLASSIFIED (first: ${unclassified.slice(0, 5).join(", ")}) — no delta is computable`);
  }
  L.assertPopulation(pop);
  for (const [c, s] of Object.entries(cats)) {
    if (s.categorized !== s.pinned + s.transformed + s.delta) throw new L.OracleRefusal(`category ${c}: arithmetic does not hold (${JSON.stringify(s)})`);
  }

  // The codemod's OWN current delta (read-only buildLedgerAndPlan; no file is written) for side-by-side comparison.
  let codemodDelta = null;
  try {
    const built = codemod.buildLedgerAndPlan({ root, partition });
    const d = built.categoryDelta;
    codemodDelta = {
      perCategory: codemod.describeCategoryDelta(d),
      categorized: codemod.OCCURRENCE_CATEGORIES.reduce((a, c) => a + d[c].categorized, 0),
      delta: codemod.OCCURRENCE_CATEGORIES.reduce((a, c) => a + d[c].delta, 0),
      uncomputable: built.categoryUncomputable.length,
      problems: codemod.categoryDeltaProblems(built),
    };
  } catch (e) {
    codemodDelta = { error: e.message };
  }

  return { head, pop, cats, uncomputable, deltaRows, compatLine, changelogBooleanOnly, codemodDelta };
}

function format(r, codemod) {
  const out = [];
  const tot = { categorized: 0, pinned: 0, transformed: 0, delta: 0 };
  for (const s of Object.values(r.cats)) for (const k of Object.keys(tot)) tot[k] += s[k];
  out.push(`ORACLE (iii) — category delta at OCCURRENCE grain over ALL lines, compat lines INCLUDED (S-OS-06 r4 STAGE 1, measurement only)`);
  out.push(`  measured head: ${r.head.sha} (${r.head.branch}); tracked tree clean`);
  out.push(`  needle: /${L.SLUG}/gi; categories: the codemod's OCCURRENCE_CATEGORIES; rule: categorized == pinned + transformed + delta, per category`);
  out.push(...L.formatPopulation(r.pop));
  out.push(`  PER CATEGORY (occurrences):`);
  for (const [c, s] of Object.entries(r.cats)) {
    const by = L.sortedEntries(s.pinnedBy).map(([k, v]) => `${k}=${v}`).join(", ");
    out.push(
      `    ${c.padEnd(16)} categorized=${String(s.categorized).padStart(5)} == pinned=${String(s.pinned).padStart(5)} + transformed=${String(s.transformed).padStart(5)} + delta=${String(s.delta).padStart(4)}  [holds=true]${by ? `  pinned-by {${by}}` : ""}`
    );
  }
  out.push(`  TOTALS: categorized=${tot.categorized} == pinned=${tot.pinned} + transformed=${tot.transformed} + delta=${tot.delta}; uncomputable=${r.uncomputable.length}`);
  out.push(`    of pinned: absolved ONLY by the changelog-historical inline boolean (no registered disposition) = ${r.changelogBooleanOnly}`);
  out.push(
    `  COMPAT-LINE OCCURRENCES now inside the delta (the codemod's whole-line skip at rename-mc.js:671 excludes these): occurrences=${r.compatLine.occurrences} pinned=${r.compatLine.pinned} transformed=${r.compatLine.transformed} delta=${r.compatLine.delta} uncomputable=${r.compatLine.uncomputable}`
  );
  if (r.codemodDelta && !r.codemodDelta.error) {
    out.push(
      `  CODEMOD'S OWN CURRENT DELTA (buildLedgerAndPlan, compat lines skipped whole): categorized=${r.codemodDelta.categorized} delta=${r.codemodDelta.delta} uncomputable=${r.codemodDelta.uncomputable} problems=${JSON.stringify(r.codemodDelta.problems)}`
    );
    out.push(`    ${r.codemodDelta.perCategory}`);
    out.push(`    categorized difference (oracle − codemod) = ${tot.categorized - r.codemodDelta.categorized} occurrence(s)`);
  } else {
    out.push(`  CODEMOD'S OWN CURRENT DELTA: unavailable (${r.codemodDelta && r.codemodDelta.error})`);
  }
  if (r.deltaRows.length) {
    out.push(`  DELTA OCCURRENCES (first ${Math.min(50, r.deltaRows.length)} of ${r.deltaRows.length}):`);
    for (const d of r.deltaRows.slice(0, 50)) out.push(`    ${d.file}:${d.line}:${d.col} [${d.category}] ${d.reason}${d.onCompatLine ? " (compat line)" : ""} "${d.matchText}" :: ${d.text}`);
  }
  if (r.uncomputable.length) {
    out.push(`  UNCOMPUTABLE (first ${Math.min(50, r.uncomputable.length)} of ${r.uncomputable.length}):`);
    for (const u of r.uncomputable.slice(0, 50)) out.push(`    ${u.file}:${u.line} [${u.category}]`);
  }
  out.push(`  VERDICT: delta=${tot.delta} uncomputable=${r.uncomputable.length} — over categorized=${tot.categorized} occurrences in scanned=${r.pop.terms.scanned} Class-1 live files (eligible ${r.pop.eligible})`);
  return { lines: out, code: tot.delta === 0 && r.uncomputable.length === 0 ? 0 : 1 };
}

if (require.main === module) {
  L.runCli(NAME, (args, lines) => {
    const r = measure({});
    const f = format(r);
    lines.push(...f.lines);
    return { code: f.code };
  });
}

module.exports = { measure, format };
